using System;
using System.Collections.Generic;
using System.IO;
using System.Linq;
using System.Text;
using Mono.Cecil;

namespace OfflineChecks
{
    /// <summary>
    /// One line per public type and per member a dependent mod can reach: public members, and
    /// protected ones of a type that can be derived from. Lines are grouped by type and sorted,
    /// so a diff of two snapshots is the API change.
    /// </summary>
    internal static class ApiSnapshot
    {
        public const string Header =
            "# Public API of EctypeFramework.dll: one line per public type and member, sorted.\n" +
            "# Generated by tools/offline-checks.ps1 -UpdateSnapshot; the offline checks fail when the\n" +
            "# built DLL differs from this file. Do not edit by hand.\n";

        public static List<string> Build(ModuleDefinition module)
        {
            var entries = new List<(string type, int order, string text)>();
            foreach (TypeDefinition t in module.Types)
                AddType(t, entries);
            return entries
                .OrderBy(e => e.type, StringComparer.Ordinal)
                .ThenBy(e => e.order)
                .ThenBy(e => e.text, StringComparer.Ordinal)
                .Select(e => e.order == 0 ? e.type + " : " + e.text : e.type + " :: " + e.text)
                .Distinct()
                .ToList();
        }

        private static bool Visible(TypeDefinition t)
        {
            if (t.DeclaringType == null) return t.IsPublic;
            if (!Visible(t.DeclaringType)) return false;
            return t.IsNestedPublic || ((t.IsNestedFamily || t.IsNestedFamilyOrAssembly) && !t.DeclaringType.IsSealed);
        }

        private static string Access(bool isPublic, bool isFamily, bool isFamOrAssem, TypeDefinition owner)
        {
            if (isPublic) return "public";
            if ((isFamily || isFamOrAssem) && !owner.IsSealed) return "protected";
            return null;
        }

        private static string Access(MethodDefinition m)
        {
            return Access(m.IsPublic, m.IsFamily, m.IsFamilyOrAssembly, m.DeclaringType);
        }

        private static void AddType(TypeDefinition t, List<(string, int, string)> entries)
        {
            if (!Visible(t)) return;
            string name = Format.TypeName(t);
            bool isDelegate = t.BaseType != null && t.BaseType.FullName == "System.MulticastDelegate";
            entries.Add((name, 0, TypeLine(t, isDelegate)));

            foreach (TypeDefinition n in t.NestedTypes) AddType(n, entries);
            if (isDelegate) return;

            if (t.IsEnum)
            {
                foreach (FieldDefinition f in t.Fields.Where(f => f.IsStatic && f.IsPublic))
                    entries.Add((name, 1, f.Name + " = " + Format.Constant(f.Constant, t.Fields.First(x => !x.IsStatic).FieldType)));
                return;
            }

            bool iface = t.IsInterface;
            foreach (FieldDefinition f in t.Fields)
            {
                string access = Access(f.IsPublic, f.IsFamily, f.IsFamilyOrAssembly, t);
                if (access == null) continue;
                string mods = f.IsLiteral ? "const " : (f.IsStatic ? "static " : "") + (f.IsInitOnly ? "readonly " : "");
                string text = access + " " + mods + Format.TypeName(f.FieldType) + " " + f.Name;
                if (f.IsLiteral) text += " = " + Format.Constant(f.Constant, f.FieldType);
                entries.Add((name, 1, text));
            }

            foreach (PropertyDefinition p in t.Properties)
            {
                string get = p.GetMethod != null ? Access(p.GetMethod) : null;
                string set = p.SetMethod != null ? Access(p.SetMethod) : null;
                if (get == null && set == null) continue;
                MethodDefinition any = get != null ? p.GetMethod : p.SetMethod;
                string access = get == "public" || set == "public" ? "public" : "protected";
                string accessors = (get != null ? (get != access ? get + " " : "") + "get; " : "") +
                                   (set != null ? (set != access ? set + " " : "") + "set; " : "");
                string indexer = p.HasParameters ? "this[" + string.Join(", ", p.Parameters.Select(x => Format.Parameter(x, false))) + "]" : p.Name;
                entries.Add((name, 2, (iface ? "" : access + " ") + Modifiers(any, iface) + Format.TypeName(p.PropertyType) + " " +
                                      indexer + " { " + accessors + "}"));
            }

            foreach (EventDefinition e in t.Events)
            {
                string access = e.AddMethod != null ? Access(e.AddMethod) : null;
                if (access == null) continue;
                entries.Add((name, 3, (iface ? "" : access + " ") + Modifiers(e.AddMethod, iface) + "event " +
                                      Format.TypeName(e.EventType) + " " + e.Name));
            }

            foreach (MethodDefinition m in t.Methods)
            {
                if (m.IsGetter || m.IsSetter || m.IsAddOn || m.IsRemoveOn || m.IsStatic && m.IsConstructor) continue;
                string access = Access(m);
                if (access == null) continue;
                bool ext = m.CustomAttributes.Any(a => a.AttributeType.FullName == "System.Runtime.CompilerServices.ExtensionAttribute");
                string ps = "(" + string.Join(", ", m.Parameters.Select((p, i) => Format.Parameter(p, ext && i == 0))) + ")";
                string text;
                if (m.IsConstructor) text = access + " " + Format.StripArity(t.Name) + ps;
                else
                {
                    string generic = m.HasGenericParameters ? "<" + string.Join(", ", m.GenericParameters.Select(g => g.Name)) + ">" : "";
                    text = (iface ? "" : access + " ") + Modifiers(m, iface) + Format.TypeName(m.ReturnType) + " " + m.Name + generic + ps +
                           Constraints(m.GenericParameters);
                }
                entries.Add((name, m.IsConstructor ? 4 : 5, text));
            }
        }

        private static string Modifiers(MethodDefinition m, bool iface)
        {
            if (iface) return m.IsStatic ? "static " : "";
            if (m.IsStatic) return "static ";
            if (m.IsAbstract) return "abstract ";
            if (m.IsVirtual && m.IsNewSlot && !m.IsFinal) return "virtual ";
            if (m.IsVirtual && !m.IsNewSlot) return m.IsFinal ? "sealed override " : "override ";
            return "";
        }

        private static string TypeLine(TypeDefinition t, bool isDelegate)
        {
            string access = t.DeclaringType != null && !t.IsNestedPublic ? "protected" : "public";
            if (isDelegate)
            {
                MethodDefinition invoke = t.Methods.First(m => m.Name == "Invoke");
                return access + " delegate " + Format.TypeName(invoke.ReturnType) + " " + Format.TypeName(t) + "(" +
                       string.Join(", ", invoke.Parameters.Select(p => Format.Parameter(p, false))) + ")";
            }
            string kind;
            if (t.IsEnum) kind = "enum";
            else if (t.IsInterface) kind = "interface";
            else if (t.IsValueType) kind = "struct";
            else if (t.IsAbstract && t.IsSealed) kind = "static class";
            else if (t.IsAbstract) kind = "abstract class";
            else if (t.IsSealed) kind = "sealed class";
            else kind = "class";
            var bases = new List<string>();
            if (t.BaseType != null && !t.IsEnum && !t.IsValueType && t.BaseType.FullName != "System.Object")
                bases.Add(Format.TypeName(t.BaseType));
            if (t.IsEnum) bases.Add(Format.TypeName(t.Fields.First(f => !f.IsStatic).FieldType));
            bases.AddRange(t.Interfaces.Select(i => Format.TypeName(i.InterfaceType)).OrderBy(x => x, StringComparer.Ordinal));
            return access + " " + kind + (bases.Count > 0 ? " : " + string.Join(", ", bases) : "") + Constraints(t.GenericParameters);
        }

        private static string Constraints(IEnumerable<GenericParameter> gps)
        {
            var sb = new StringBuilder();
            foreach (GenericParameter g in gps)
            {
                var c = new List<string>();
                if (g.HasReferenceTypeConstraint) c.Add("class");
                if (g.HasNotNullableValueTypeConstraint) c.Add("struct");
                c.AddRange(g.Constraints.Select(x => Format.TypeName(x.ConstraintType))
                            .Where(x => x != "System.ValueType").OrderBy(x => x, StringComparer.Ordinal));
                if (g.HasDefaultConstructorConstraint && !g.HasNotNullableValueTypeConstraint) c.Add("new()");
                if (c.Count > 0) sb.Append(" where " + g.Name + " : " + string.Join(", ", c));
            }
            return sb.ToString();
        }

        /// <summary>Reads a snapshot file without its comment header.</summary>
        public static List<string> Read(string path)
        {
            return File.ReadAllLines(path).Where(l => l.Length > 0 && !l.StartsWith("#", StringComparison.Ordinal)).ToList();
        }

        public static void Write(string path, List<string> lines)
        {
            var sb = new StringBuilder(Header);
            foreach (string l in lines) sb.Append(l).Append('\n');
            File.WriteAllText(path, sb.ToString(), new UTF8Encoding(false));
        }
    }
}
